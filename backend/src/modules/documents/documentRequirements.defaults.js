/**
 * Determines if a requirement is effectively mandatory for a specific applicant's context.
 */
export const isRequirementMandatory = (reqItem, context = {}) => {
  if (!reqItem || reqItem.isActive === false) return false;
  if (reqItem.category !== 'mandatory') return false;
  if (!reqItem.isConditional) return true;
  if (reqItem.conditionKey) {
    return Boolean(context && context[reqItem.conditionKey]);
  }
  return true;
};

/**
 * Evaluates effective requirements for a set of roles & applicant context.
 */
export const evaluateRequirementsForApplicant = (allRequirements, roles = [], context = {}) => {
  const verificationRoles = (Array.isArray(roles) ? roles : [roles]).filter((r) =>
    ['teacher', 'businessman', 'entrepreneur'].includes(r)
  );
  if (verificationRoles.length === 0) {
    return { requiresVerification: false, mandatory: [], optional: [], all: [] };
  }

  const activeReqs = (allRequirements || [])
    .filter((r) => r.isActive !== false && verificationRoles.includes(r.role))
    .sort((a, b) => (a.order || 0) - (b.order || 0));

  const seenIds = new Set();
  const evaluated = [];
  for (const r of activeReqs) {
    if (seenIds.has(r.id)) continue;
    seenIds.add(r.id);
    const effectiveMandatory = isRequirementMandatory(r, context);
    evaluated.push({
      ...r,
      effectiveMandatory,
      effectiveCategory: effectiveMandatory ? 'mandatory' : 'optional',
    });
  }

  return {
    requiresVerification: true,
    mandatory: evaluated.filter((r) => r.effectiveMandatory),
    optional: evaluated.filter((r) => !r.effectiveMandatory),
    all: evaluated,
  };
};
